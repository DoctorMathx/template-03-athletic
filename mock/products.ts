export function getProductBySlug(slug: string) {
  return products.find((p) => p.slug === slug);
}

export function getProductsByIds(ids: string[]) {
  return products.filter((p) => ids.includes(p.id));
}

export function getBestsellers(gender?: "men" | "women", limit = 10) {
  return products
    .filter((p) => (gender ? p.gender === gender : true) && p.rank !== undefined)
    .sort((a, b) => (a.rank ?? 99) - (b.rank ?? 99))
    .slice(0, limit);
}

export function getNewArrivals(gender?: "men" | "women", limit = 8) {
  return products
    .filter((p) => (gender ? p.gender === gender : true) && p.isNew)
    .slice(0, limit);
}
